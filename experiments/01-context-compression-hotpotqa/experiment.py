# 8. Per-seed driver
# ---------------------------------------------------------------------------
def run_seed(seed: int) -> dict:
    if os.environ.get("EXPERIMENT_STUB"):
        # Plumbing test path.
        canned = {
            "full":        {"f1": 0.62, "em": 0.46, "ratio": 1.00, "latency_ms": 220.0},
            "truncate":    {"f1": 0.34, "em": 0.21, "ratio": 0.30, "latency_ms": 90.0},
            "random":      {"f1": 0.31, "em": 0.18, "ratio": 0.30, "latency_ms": 90.0},
            "extractive":  {"f1": 0.51, "em": 0.36, "ratio": 0.30, "latency_ms": 110.0},
            "abstractive": {"f1": 0.49, "em": 0.32, "ratio": 0.30, "latency_ms": 540.0},
            "structured":  {"f1": 0.46, "em": 0.30, "ratio": 0.30, "latency_ms": 600.0},
            "iterative":   {"f1": 0.55, "em": 0.39, "ratio": 0.30, "latency_ms": 1300.0},
        }
        return {
            "seed": seed,
            "primary_metric_name": "f1_iterative",
            "primary_metric": canned["iterative"]["f1"],
            "training_time_s": 0.0,
            "peak_gpu_memory_gb": 0.0,
            "per_method": canned,
        }

    examples = load_examples(N_EXAMPLES, seed)
    rng = random.Random(seed)
    torch.manual_seed(seed)

    # Eagerly load models so latency timings exclude cold start.
    _load_reader()
    _load_embedder()

    method_metrics = {m: {"f1": [], "em": [], "ratio": [], "latency_ms": []}
                      for m in COMPRESSORS}

    for ex in tqdm(examples, desc=f"seed={seed}"):
        full_ctx = context_full(ex["paragraphs"], ex["question"])
        full_toks = max(1, n_tokens(full_ctx))
        for method, fn in COMPRESSORS.items():
            t0 = time.perf_counter()
            ctx = fn(ex["paragraphs"], ex["question"], TARGET_RATIO, rng)
            comp_dt = (time.perf_counter() - t0) * 1000.0
            ctx_toks = max(1, n_tokens(ctx))
            t1 = time.perf_counter()
            pred = answer_question(ctx, ex["question"])
            qa_dt = (time.perf_counter() - t1) * 1000.0
            method_metrics[method]["f1"].append(f1_score(pred, ex["answer"]))
            method_metrics[method]["em"].append(em_score(pred, ex["answer"]))
            method_metrics[method]["ratio"].append(ctx_toks / full_toks)
            method_metrics[method]["latency_ms"].append(comp_dt + qa_dt)

    per_method = {}
    for method, metrics in method_metrics.items():
        per_method[method] = {
            "f1": float(np.mean(metrics["f1"])),
            "em": float(np.mean(metrics["em"])),
            "ratio": float(np.mean(metrics["ratio"])),
            "latency_ms": float(np.mean(metrics["latency_ms"])),
            "n": len(metrics["f1"]),
        }

    # Primary metric of the paper = F1 of the best learned compressor (iterative)
    # on this seed. Headline mean/std across seeds reported in summary.
    primary = per_method["iterative"]["f1"]

    peak_mem = 0.0
    if torch.cuda.is_available():
        peak_mem = float(torch.cuda.max_memory_allocated()) / (1024 ** 3)
        torch.cuda.reset_peak_memory_stats()

    result = {
        "seed": seed,
        "primary_metric_name": "f1_iterative",
        "primary_metric": primary,
        "training_time_s": 0.0,
        "peak_gpu_memory_gb": peak_mem,
        "per_method": per_method,
        "n_examples": len(examples),
    }
    print(f"RESULT: metric={primary:.4f} seed={seed}", flush=True)
    return result


