# Cache model handles globally so all seeds share the same load.
_READER = None
_TOKENIZER = None
_EMBEDDER = None


def _load_reader():
    global _READER, _TOKENIZER
    if _READER is not None:
        return _TOKENIZER, _READER
    from transformers import AutoModelForCausalLM, AutoTokenizer

    _TOKENIZER = AutoTokenizer.from_pretrained(READER_MODEL_NAME)
    if _TOKENIZER.pad_token_id is None:
        _TOKENIZER.pad_token_id = _TOKENIZER.eos_token_id
    _READER = AutoModelForCausalLM.from_pretrained(
        READER_MODEL_NAME,
        torch_dtype=torch.float16 if DEVICE == "cuda" else torch.float32,
    ).to(DEVICE)
    _READER.eval()
    return _TOKENIZER, _READER


def _load_embedder():
    global _EMBEDDER
    if _EMBEDDER is not None:
        return _EMBEDDER
    from sentence_transformers import SentenceTransformer

    _EMBEDDER = SentenceTransformer(EMBED_MODEL_NAME, device=DEVICE)
    return _EMBEDDER


# ---------------------------------------------------------------------------
# 4. Generation helpers
# ---------------------------------------------------------------------------
@torch.no_grad()
def llm_chat(prompt: str, max_new_tokens: int = 64, temperature: float = 0.0) -> str:
    tok, model = _load_reader()
    messages = [{"role": "user", "content": prompt}]
    text = tok.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    inputs = tok(text, return_tensors="pt").to(DEVICE)
    do_sample = temperature > 0.0
    out = model.generate(
        **inputs,
        max_new_tokens=max_new_tokens,
        do_sample=do_sample,
        temperature=max(temperature, 1e-4) if do_sample else 1.0,
        pad_token_id=tok.pad_token_id,
        eos_token_id=tok.eos_token_id,
    )
    new_tokens = out[0][inputs["input_ids"].shape[1] :]
    return tok.decode(new_tokens, skip_special_tokens=True).strip()


def n_tokens(text: str) -> int:
    tok, _ = _load_reader()
    return len(tok.encode(text, add_special_tokens=False))


# ---------------------------------------------------------------------------
# 5. Compression methods
# ---------------------------------------------------------------------------
def _split_sentences(text: str) -> List[str]:
    # Light-weight sentence splitter; HotpotQA paragraphs are typically clean.
    sents = re.split(r"(?<=[.!?])\s+", text.strip())
    return [s for s in sents if s]


def context_full(paragraphs: List[Tuple[str, List[str]]], question: str) -> str:
    return "\n\n".join(f"{title}: {' '.join(sents)}" for title, sents in paragraphs)


def context_truncate(
    paragraphs: List[Tuple[str, List[str]]], question: str, ratio: float
) -> str:
    full = context_full(paragraphs, question)
    target_toks = max(16, int(n_tokens(full) * ratio))
    tok, _ = _load_reader()
    ids = tok.encode(full, add_special_tokens=False)[:target_toks]
    return tok.decode(ids, skip_special_tokens=True)


def context_random(
    paragraphs: List[Tuple[str, List[str]]],
    question: str,
    ratio: float,
    rng: random.Random,
) -> str:
    k = max(1, int(round(len(paragraphs) * ratio)))
    chosen = rng.sample(paragraphs, k)
    return "\n\n".join(f"{t}: {' '.join(s)}" for t, s in chosen)


def context_extractive(
    paragraphs: List[Tuple[str, List[str]]], question: str, ratio: float
) -> str:
    embedder = _load_embedder()
    # Score each paragraph by max sentence-question cosine similarity.
    q_emb = embedder.encode([question], convert_to_numpy=True, normalize_embeddings=True)[0]
    scored = []
    for title, sents in paragraphs:
        if not sents:
            continue
        embs = embedder.encode(sents, convert_to_numpy=True, normalize_embeddings=True)
        score = float(np.max(embs @ q_emb))
        scored.append((score, title, sents))
    scored.sort(key=lambda x: x[0], reverse=True)
    k = max(1, int(round(len(paragraphs) * ratio)))
    top = scored[:k]
    return "\n\n".join(f"{t}: {' '.join(s)}" for _, t, s in top)


def context_abstractive(
    paragraphs: List[Tuple[str, List[str]]], question: str, ratio: float
) -> str:
    full = context_full(paragraphs, question)
    target_toks = max(32, int(n_tokens(full) * ratio))
    prompt = (
        "You compress reference passages so a downstream reader can still "
        "answer a question. Preserve named entities, dates, numbers, and "
        "explicit relations exactly; drop anything irrelevant.\n\n"
        f"Question (for relevance only — do NOT answer it):\n{question}\n\n"
        f"Passages:\n{full}\n\n"
        f"Write a single compressed passage of at most {target_toks} tokens. "
        "Output only the compressed passage, no preamble."
    )
    return llm_chat(prompt, max_new_tokens=target_toks + 32)


def context_structured(
    paragraphs: List[Tuple[str, List[str]]], question: str, ratio: float
) -> str:
    full = context_full(paragraphs, question)
    prompt = (
        "Extract a structured memory from the passages as a JSON object with "
        'keys "entities" (list of {name, type}), "relations" (list of '
        '{subject, predicate, object}), and "facts" (list of short factual '
        "strings). Cover only items that could be useful for the question. "
        "Output ONLY valid JSON.\n\n"
        f"Question:\n{question}\n\nPassages:\n{full}"
    )
    target_toks = max(96, int(n_tokens(full) * ratio))
    raw = llm_chat(prompt, max_new_tokens=target_toks + 64)
    # Try to parse; if invalid, fall back to raw text — downstream reader
    # tolerates either.
    try:
        obj = _json.loads(raw[raw.find("{") : raw.rfind("}") + 1])
        ents = ", ".join(
            f"{e.get('name','')}({e.get('type','')})" for e in obj.get("entities", [])
        )
        rels = "; ".join(
            f"{r.get('subject','')} {r.get('predicate','')} {r.get('object','')}"
            for r in obj.get("relations", [])
        )
        facts = " | ".join(obj.get("facts", []))
        return f"ENTITIES: {ents}\nRELATIONS: {rels}\nFACTS: {facts}"
    except Exception:
        return raw


def context_iterative(
    paragraphs: List[Tuple[str, List[str]]], question: str, ratio: float
) -> str:
    # Round 1 — per-paragraph short summary (cap each at ~40 tokens).
    per_para = []
    for title, sents in paragraphs:
        if not sents:
            continue
        para = f"{title}: {' '.join(sents)}"
        prompt = (
            "Summarize the passage in <=2 short factual sentences. "
            "Keep entities, dates, and numbers verbatim.\n\n"
            f"Passage:\n{para}"
        )
        summary = llm_chat(prompt, max_new_tokens=80)
        per_para.append(summary)
    round1 = "\n".join(f"- {s}" for s in per_para)
    # Round 2 — compact relevant points for the question.
    full_orig = context_full(paragraphs, question)
    target_toks = max(32, int(n_tokens(full_orig) * ratio))
    prompt = (
        "From the bullet summaries below, write a single compressed passage "
        f"of at most {target_toks} tokens that retains every fact relevant "
        "to the question. Keep entities, dates, and numbers exact.\n\n"
        f"Question:\n{question}\n\nBullets:\n{round1}\n\nCompressed passage:"
    )
    return llm_chat(prompt, max_new_tokens=target_toks + 32)


COMPRESSORS: Dict[str, Callable] = {
    "full": lambda p, q, r, rng: context_full(p, q),
    "truncate": lambda p, q, r, rng: context_truncate(p, q, r),
    "random": lambda p, q, r, rng: context_random(p, q, r, rng),
    "extractive": lambda p, q, r, rng: context_extractive(p, q, r),
    "abstractive": lambda p, q, r, rng: context_abstractive(p, q, r),
    "structured": lambda p, q, r, rng: context_structured(p, q, r),
    "iterative": lambda p, q, r, rng: context_iterative(p, q, r),
}


# ---------------------------------------------------------------------------
# 6. QA prompting + evaluation
# ---------------------------------------------------------------------------
def answer_question(context: str, question: str) -> str:
    prompt = (
        "Answer the question using ONLY the context. Reply with the shortest "
        "exact answer span (no explanation). If the answer cannot be found, "
        'reply "unknown".\n\n'
        f"Context:\n{context}\n\nQuestion: {question}\nAnswer:"
    )
    return llm_chat(prompt, max_new_tokens=MAX_NEW_TOKENS_QA)


# SQuAD-style normalization (Rajpurkar 2016).
def _normalize(s: str) -> str:
    s = s.lower()
    s = re.sub(r"\b(a|an|the)\b", " ", s)
    s = "".join(c for c in s if c not in set(string.punctuation))
    return " ".join(s.split())


def f1_score(pred: str, gold: str) -> float:
    p_tokens = _normalize(pred).split()
    g_tokens = _normalize(gold).split()
    if not p_tokens or not g_tokens:
        return float(p_tokens == g_tokens)
    common = Counter(p_tokens) & Counter(g_tokens)
    overlap = sum(common.values())
    if overlap == 0:
        return 0.0
    precision = overlap / len(p_tokens)
    recall = overlap / len(g_tokens)
    return 2 * precision * recall / (precision + recall)


def em_score(pred: str, gold: str) -> float:
    return float(_normalize(pred) == _normalize(gold))


