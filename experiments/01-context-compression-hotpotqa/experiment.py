# 9. Aggregation, figures, summary.json
# ---------------------------------------------------------------------------
def _aggregate(results: List[dict]) -> dict:
    methods = list(results[0]["per_method"].keys())
    agg = {}
    for m in methods:
        f1s = [r["per_method"][m]["f1"] for r in results]
        ems = [r["per_method"][m]["em"] for r in results]
        ratios = [r["per_method"][m]["ratio"] for r in results]
        lats = [r["per_method"][m]["latency_ms"] for r in results]
        agg[m] = {
            "f1_mean": float(np.mean(f1s)),
            "f1_std": float(np.std(f1s)),
            "em_mean": float(np.mean(ems)),
            "em_std": float(np.std(ems)),
            "ratio_mean": float(np.mean(ratios)),
            "ratio_std": float(np.std(ratios)),
            "latency_ms_mean": float(np.mean(lats)),
        }
    return agg


def _draw_figures(agg: dict) -> None:
    methods = ["full", "truncate", "random", "extractive",
               "abstractive", "structured", "iterative"]
    f1_means = [agg[m]["f1_mean"] for m in methods]
    f1_stds = [agg[m]["f1_std"] for m in methods]
    ratio_means = [agg[m]["ratio_mean"] for m in methods]
    em_means = [agg[m]["em_mean"] for m in methods]

    # Figure 1 — F1 by method.
    fig, ax = plt.subplots(figsize=(7.0, 3.6))
    bars = ax.bar(methods, f1_means, yerr=f1_stds, capsize=4,
                  color=["#888"] + ["#aab"] * 2 + ["#4477aa", "#ee6677",
                                                    "#228833", "#ccbb44"])
    ax.set_ylabel("HotpotQA F1")
    ax.set_ylim(0.0, max(0.7, max(f1_means) + 0.1))
    ax.set_title("Answer F1 by compression method")
    for b, m in zip(bars, f1_means):
        ax.text(b.get_x() + b.get_width() / 2, m + 0.01, f"{m:.2f}",
                ha="center", va="bottom", fontsize=9)
    plt.xticks(rotation=20, ha="right")
    plt.tight_layout()
    plt.savefig(ART / "figures" / "f1_by_method.png", dpi=200)
    plt.close(fig)

    # Figure 2 — F1 vs compression ratio scatter.
    fig, ax = plt.subplots(figsize=(6.0, 4.0))
    for m in methods:
        ax.scatter(agg[m]["ratio_mean"], agg[m]["f1_mean"], s=80, label=m)
        ax.annotate(m, (agg[m]["ratio_mean"], agg[m]["f1_mean"]),
                    textcoords="offset points", xytext=(6, 4), fontsize=9)
    ax.set_xlabel("Compression ratio (kept / original tokens)")
    ax.set_ylabel("HotpotQA F1")
    ax.set_title("Quality vs. compression frontier")
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(ART / "figures" / "f1_vs_ratio.png", dpi=200)
    plt.close(fig)

    # Figure 3 — F1 and EM side-by-side.
    fig, ax = plt.subplots(figsize=(7.0, 3.6))
    x = np.arange(len(methods))
    w = 0.4
    ax.bar(x - w / 2, f1_means, width=w, label="F1", color="#4477aa")
    ax.bar(x + w / 2, em_means, width=w, label="EM", color="#ee6677")
    ax.set_xticks(x)
    ax.set_xticklabels(methods, rotation=20, ha="right")
    ax.set_ylabel("Score")
    ax.set_title("F1 and Exact Match by method")
    ax.legend()
    plt.tight_layout()
    plt.savefig(ART / "figures" / "f1_em_by_method.png", dpi=200)
    plt.close(fig)


def _write_table(agg: dict) -> None:
    methods = ["full", "truncate", "random", "extractive",
               "abstractive", "structured", "iterative"]
    lines = ["method,f1_mean,f1_std,em_mean,em_std,ratio_mean,latency_ms_mean"]
    for m in methods:
        a = agg[m]
        lines.append(
            f"{m},{a['f1_mean']:.4f},{a['f1_std']:.4f},"
            f"{a['em_mean']:.4f},{a['em_std']:.4f},"
            f"{a['ratio_mean']:.4f},{a['latency_ms_mean']:.2f}"
        )
    (ART / "tables" / "compression_methods.csv").write_text("\n".join(lines))


