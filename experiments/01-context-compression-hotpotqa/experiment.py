# 7. Dataset loader
# ---------------------------------------------------------------------------
def load_examples(n: int, seed: int):
    from datasets import load_dataset

    ds = load_dataset("hotpot_qa", "distractor", split="validation")
    rng = random.Random(seed)
    indices = list(range(len(ds)))
    rng.shuffle(indices)
    chosen = indices[:n]
    out = []
    for i in chosen:
        ex = ds[i]
        ctx = ex["context"]
        # ctx['title']: List[str], ctx['sentences']: List[List[str]]
        paras = list(zip(ctx["title"], ctx["sentences"]))
        out.append(
            {
                "id": ex["id"],
                "question": ex["question"],
                "answer": ex["answer"],
                "paragraphs": paras,
            }
        )
    return out


