READER_MODEL_NAME = os.environ.get("READER_MODEL", "Qwen/Qwen2.5-1.5B-Instruct")
EMBED_MODEL_NAME = os.environ.get(
    "EMBED_MODEL", "sentence-transformers/all-MiniLM-L6-v2"
)
N_EXAMPLES = int(os.environ.get("N_EXAMPLES", "100"))
TARGET_RATIO = float(os.environ.get("TARGET_RATIO", "0.30"))  # ~30% of original
MAX_NEW_TOKENS_QA = int(os.environ.get("MAX_NEW_TOKENS_QA", "32"))
